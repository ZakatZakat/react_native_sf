"""Фильтр политической / антиправительственной «запрещёнки».

Заказчик работает на РФ-аудиторию — события про политзаключённых, антивоенные
акции, митинги/пикеты и признанных «иноагентами/экстремистами» лиц в ленту не
пускаем (юр-риск). Детектор помечает такой пост political=True, процессор кладёт
его в rejected (не публикует).

Паттерн подобран на ПРЕЦИЗИЮ — ключевое здесь не пропустить «запрещёнку», но и
не зарубить легальные события с похожими подстроками. Регрессия на реальные
ложные срабатывания из прод-базы:
  • «карНАВАЛЬНый» сап-заплыв        (не «Навальный»)
  • лекция Сергея Кара-Мурзы          (социолог, не политзек Кара-Мурза)
  • премия «Просветитель» со словом «иноагент» в редакционном сарказме
  • МИТАП по Python                   (не «митинг»), сПИКЕр (не «пикет»)
"""

from app.pipeline.detector import detect_event, looks_political

# Реальный пост из ленты (id 4494) — то, ради чего фильтр и делался.
LETTERS_TO_PRISONERS = (
    "привет! приглашаем вас на вечер писем политзаключенным!\n\n"
    "приходите писать письма в любое время с 17 до 21 во вторник (28.07)\n"
    "чтобы узнать место встречи, пишите нам в личные сообщения канала"
)

POLITICAL_TEXTS = [
    LETTERS_TO_PRISONERS,
    "Три года с момента заключения Бориса Кагарлицкого. Вечер солидарности с политзаключёнными.",
    "Антивоенный вечер поэзии, 19:00, приходите — против войны.",
    "Показ фильма о Навальном и ФБК, обсуждение после.",
    "Пикет в поддержку политзаключённых на Пушкинской, 18:00.",
    "Свободу политзаключённым! Встреча правозащитников, вход свободный.",
    "Митинг за честные выборы, сбор у метро в 14:00.",
]

# Легальные события с «опасными» подстроками — НЕ должны попадать под фильтр.
LEGIT_TEXTS = [
    "Концерт группы Аквариум 12 августа в 19:00, клуб «16 тонн».",
    "Карнавальный сап-заплыв на Яузе — море драйва и музыки, 9 августа!",
    "Лекция историка Сергея Кара-Мурзы о советской цивилизации, вход свободный.",
    "Опубликован лонг-лист премии «Просветитель» — до иноагентов и либералов дошло, что научпоп жив.",
    "Митап по Python: доклады и нетворкинг, 20:00, коворкинг «Ключ».",
    "Спикер вечера — известный режиссёр. Пикник в парке Горького, 15:00.",
    "Выставка живописи «Одиссея» Гомера, Страдариум, суббота 12:00.",
]


def test_political_flagged():
    for t in POLITICAL_TEXTS:
        assert looks_political(t), f"должно быть political: {t[:60]!r}"
        det = detect_event(t)
        assert det.political is True
        assert "political" in det.reasons
        # political-пост никогда не должен считаться публикуемым событием
        assert det.is_event_review is False
        assert det.is_event_auto is False


def test_legit_not_flagged():
    for t in LEGIT_TEXTS:
        assert not looks_political(t), f"НЕ должно быть political: {t[:60]!r}"
        assert detect_event(t).political is False


def test_empty_text_safe():
    det = detect_event("")
    assert det.political is False
